#!/usr/bin/env python3
"""Pack captured ViT parameters and link the Triton-call graph for NR.

The ELF contains code and a small input/output buffer. Parameters occupy a
NOLOAD arena at the linker's HIGH DDR base and are uploaded separately with
the generated DDR load plan. An ELF audit is a static ISA check, not a board
execution result.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import shutil
import subprocess
import sys

ELEMENTS = 86_567_656
WEIGHT_BYTES = ELEMENTS * 4
IMAGE_BYTES = 1 * 3 * 224 * 224 * 4
WORKSPACE_BASE = 0xB8000000
BOOT_BASE = 0x80000000
WORKSPACE_ALIGN = 64


def align64(value: int) -> int:
    return (value + 63) & ~63


def digest_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def trace_call_count(adapters: Path) -> int:
    """Reject an old adapter when a traced image was requested."""
    source = adapters.read_text()
    match = re.search(r"^#define VIT_TRACE_CALL_COUNT (\d+)$", source, re.M)
    if match is None or "#define VIT_TRACE_MARK(message) nr_puts(message)" not in source:
        raise ValueError("--trace-ops requires adapters regenerated by replace_triton.py")
    count = int(match.group(1))
    if (count < 1 or source.count(' BEGIN\\r\\n");') != count or
            source.count(' END\\r\\n");') != count):
        raise ValueError("adapter BEGIN/END marker count does not match graph calls")
    return count


def tensor_bytes(tensor) -> bytes:
    # SafeTensors exposes little-endian FP32 tensors on this target host.
    if str(tensor.dtype) != "torch.float32":
        raise ValueError(f"expected float32 tensor, got {tensor.dtype}")
    return tensor.contiguous().numpy().tobytes(order="C")


def quantize_weight_bytes(tensor):
    """Return physical [N,K] signed-i8 rows and per-output scales."""
    import numpy as np
    array = tensor.detach().cpu().contiguous().numpy().astype(np.float32, copy=False)
    if array.ndim != 2:
        raise ValueError(f"linear weight must be rank-2, got {array.shape}")
    maximum = np.max(np.abs(array), axis=1)
    scales = np.where(maximum == 0.0, 1.0, maximum / 127.0).astype(np.float32)
    ratio = array / scales[:, None]
    # Triton uses ties-away-from-zero.  Use the unrounded sign so that a
    # negative value whose rounded representation is -0.0 still follows the
    # negative branch.
    values = np.where(ratio >= 0, np.floor(ratio + 0.5),
                      np.ceil(ratio - 0.5))
    values = np.clip(values, -127, 127).astype(np.int8)
    return values.tobytes(order="C"), scales.tobytes(order="C")


def _align_file(path: Path) -> tuple[int, str]:
    size = path.stat().st_size
    padded = align64(size)
    if padded > size:
        with path.open("ab") as stream:
            stream.write(bytes(padded - size))
    return padded, digest_file(path)


def _pack_fp32_weights(params: Path, checkpoint: Path, output: Path) -> dict:
    from safetensors import safe_open

    records = json.loads(params.read_text())
    if not isinstance(records, list) or len(records) != 200:
        raise ValueError("expected 200 captured ViT parameter records")
    if [record.get("index") for record in records] != list(range(len(records))):
        raise ValueError("captured parameter indices must be consecutive")
    if any(record.get("dtype") != "float32" or
           record.get("elements") != math.prod(record.get("shape", []))
           for record in records):
        raise ValueError("captured parameter shapes or dtypes are invalid")
    if sum(record["elements"] for record in records) != ELEMENTS:
        raise ValueError("captured parameter count disagrees with the graph ABI")

    # Match by content as well as shape: the flattened graph order differs
    # from SafeTensors key order, and names can differ across Transformers.
    candidates = {}
    with safe_open(str(checkpoint), framework="pt", device="cpu") as archive:
        for name in archive.keys():
            tensor = archive.get_tensor(name)
            raw = tensor_bytes(tensor)
            key = (tuple(tensor.shape), hashlib.sha256(raw).hexdigest())
            candidates.setdefault(key, []).append(name)
    for names in candidates.values():
        names.sort()

    weights_path = output / "weights.bin"
    sections = []
    offset = 0
    stream_hash = hashlib.sha256()
    with safe_open(str(checkpoint), framework="pt", device="cpu") as archive, \
            weights_path.open("wb") as dest:
        for record in records:
            key = (tuple(record["shape"]), record["sha256"])
            names = candidates.get(key)
            if not names:
                raise ValueError(f"checkpoint has no match for parameter {record['index']}")
            name = names[0]  # Equal hashes imply equal bytes, including tied weights.
            raw = tensor_bytes(archive.get_tensor(name))
            if len(raw) != record["elements"] * 4 or \
                    hashlib.sha256(raw).hexdigest() != record["sha256"]:
                raise ValueError(f"parameter {record['index']} changed while packing")
            dest.write(raw)
            stream_hash.update(raw)
            sections.append({"index": record["index"], "checkpoint_key": name,
                             "shape": record["shape"], "offset_elements": offset // 4,
                             "offset_bytes": offset, "bytes": len(raw),
                             "sha256": record["sha256"]})
            offset += len(raw)
    if offset != WEIGHT_BYTES or weights_path.stat().st_size != WEIGHT_BYTES:
        raise ValueError(f"weight byte count {offset} does not match {WEIGHT_BYTES}")
    load_path = output / "weights-load.bin"
    with weights_path.open("rb") as source, load_path.open("wb") as dest:
        shutil.copyfileobj(source, dest, 1024 * 1024)
        dest.write(bytes(align64(offset) - offset))
    manifest = {
        "parameter_count": len(records), "elements": ELEMENTS,
        "bytes": offset, "sha256": stream_hash.hexdigest(),
        "file": weights_path.name, "load_file": load_path.name,
        "load_bytes": load_path.stat().st_size,
        "load_sha256": digest_file(load_path), "load_address": hex(WORKSPACE_BASE),
        "sections": sections,
    }
    (output / "weight-load.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def _pack_w8a8_weights(params: Path, checkpoint: Path, output: Path,
                       replacement: Path) -> dict:
    """Pack surviving FP32 parameters and W8A8 matrices into typed arenas."""
    from safetensors import safe_open
    import numpy as np

    records = json.loads(params.read_text())
    report_path = replacement / "triton-call-replacement.json"
    report = json.loads(report_path.read_text())
    layout = report.get("parameter_layout")
    linears = report.get("w8a8_linears") or []
    original_names = report.get("original_parameters")
    if not isinstance(layout, list) or not linears or not isinstance(original_names, list):
        raise ValueError("W8A8 replacement report lacks parameter_layout/original_parameters")
    if len(records) != len(original_names):
        raise ValueError("params.json and replacement original_parameters disagree")
    by_name = {name: records[i] for i, name in enumerate(original_names)}
    qmap = {entry["weight_param_name"]: entry for entry in linears}
    smap = {entry["scale_param_name"]: entry for entry in linears}

    # Resolve checkpoint tensors by captured shape+content, exactly as the
    # FP32 path does.  This handles renamed Transformers keys and tied values.
    candidates = {}
    with safe_open(str(checkpoint), framework="pt", device="cpu") as archive:
        for name in archive.keys():
            tensor = archive.get_tensor(name)
            raw = tensor_bytes(tensor)
            candidates.setdefault((tuple(tensor.shape), hashlib.sha256(raw).hexdigest()), []).append(name)
    for names in candidates.values():
        names.sort()

    tensors = {}
    with safe_open(str(checkpoint), framework="pt", device="cpu") as archive:
        for name, record in by_name.items():
            names = candidates.get((tuple(record["shape"]), record["sha256"]))
            if not names:
                raise ValueError(f"checkpoint has no match for parameter {record['index']} ({name})")
            tensors[name] = archive.get_tensor(names[0])

    # Generate each quantized matrix once; report entries map the new graph
    # placeholders back to their captured FP32 source parameter.
    quantized = {}
    scales = {}
    for entry in linears:
        source = entry["weight_param"]
        qraw, sraw = quantize_weight_bytes(tensors[source])
        quantized[entry["weight_param_name"]] = qraw
        scales[entry["scale_param_name"]] = sraw

    f32_path = output / "weights-f32.bin"
    i8_path = output / "weights-i8.bin"
    f32_sections, i8_sections = [], []
    f32_offset = i8_offset = 0
    with f32_path.open("wb") as f32, i8_path.open("wb") as i8:
        for item in layout:
            name, dtype = item["name"], item["dtype"]
            if "Int8" in dtype or dtype.endswith("i8"):
                raw = quantized.get(name)
                if raw is None:
                    raise ValueError(f"no quantized bytes for graph parameter {name}")
                i8.write(raw)
                i8_sections.append({"name": name, "dtype": "i8", "shape": item["shape"],
                                    "offset_bytes": i8_offset, "bytes": len(raw)})
                i8_offset += len(raw)
            elif "Float32" in dtype or dtype.endswith("f32"):
                raw = scales.get(name)
                source = None
                if raw is None:
                    source = name
                    record = by_name.get(source)
                    if record is None:
                        raise ValueError(f"graph FP32 parameter {name} has no captured source")
                    raw = tensor_bytes(tensors[source])
                expected = math.prod(item["shape"]) * 4
                if len(raw) != expected:
                    raise ValueError(f"parameter {name} byte size {len(raw)} != {expected}")
                f32.write(raw)
                f32_sections.append({"name": name, "dtype": "f32", "shape": item["shape"],
                                     "offset_bytes": f32_offset, "bytes": len(raw),
                                     **({"source": source} if source else {"source": "quantized_weight_scale"})})
                f32_offset += len(raw)
            else:
                raise ValueError(f"unsupported graph parameter dtype {dtype} ({name})")
    f32_load, f32_hash = _align_file(f32_path)
    i8_load, i8_hash = _align_file(i8_path)
    manifest = {
        "mode": "w8a8", "parameter_count": len(layout),
        "original_parameter_count": len(records),
        "arenas": [
            {"name": "weights-f32", "dtype": "f32", "file": f32_path.name,
             "bytes": f32_offset, "load_file": f32_path.name,
             "load_bytes": f32_load, "load_sha256": f32_hash,
             "sections": f32_sections},
            {"name": "weights-i8", "dtype": "i8", "file": i8_path.name,
             "bytes": i8_offset, "load_file": i8_path.name,
             "load_bytes": i8_load, "load_sha256": i8_hash,
             "sections": i8_sections},
        ],
        "elements_f32": f32_offset // 4, "elements_i8": i8_offset,
        "replacement_report": str(report_path),
    }
    (output / "weight-load.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def pack_weights(params: Path, checkpoint: Path, output: Path,
                 replacement: Path | None = None) -> dict:
    if replacement is not None and (replacement / "triton-call-replacement.json").is_file():
        report = json.loads((replacement / "triton-call-replacement.json").read_text())
        if report.get("w8a8_enabled"):
            return _pack_w8a8_weights(params, checkpoint, output, replacement)
    return _pack_fp32_weights(params, checkpoint, output)


def verify_subgraph_abi(graph_ir: Path, source: Path | None,
                        replacement: Path | None = None) -> dict:
    """Reject stale captures that added extra input tensors to the ViT graph."""
    if source is None:
        lower_report = graph_ir.parent / "lower.json"
        if not lower_report.is_file():
            raise ValueError("pass --subgraph-mlir or provide lower.json beside graph IR")
        source = Path(json.loads(lower_report.read_text())["source"])
    match = re.search(r"func\.func @vit\((.*?)\)\s*->", source.read_text(), re.S)
    if not match:
        raise ValueError(f"ViT entry signature is missing from {source}")
    count = len(re.findall(r"%arg\d+:", match.group(1)))
    expected = 201
    if replacement is not None and (replacement / "triton-call-replacement.json").is_file():
        report = json.loads((replacement / "triton-call-replacement.json").read_text())
        if report.get("w8a8_enabled"):
            expected = 1 + len(report.get("parameter_layout", [])) + \
                      len(report.get("w8a8_workspace_inputs", []))
    if count != expected:
        raise ValueError(f"ViT subgraph has {count} inputs; expected {expected}")
    if "1x3x224x224xf32" not in match.group(1).split(",", 1)[0]:
        raise ValueError("ViT subgraph first input is not the fixed FP32 image")
    return {"source": str(source), "inputs": count,
            "image_shape": [1, 3, 224, 224],
            "parameter_inputs": expected - 1}


def verify_main_weight_layout(main_ir: Path, source: Path | None,
                              params: Path, replacement: Path | None = None) -> dict:
    """Match every flat-buffer slice to the captured parameter order."""
    source = source or main_ir.with_name("main.ciface.mlir")
    if not source.is_file():
        raise ValueError(f"main graph MLIR is missing: {source}")
    text = source.read_text()
    if replacement is not None and (replacement / "triton-call-replacement.json").is_file():
        report = json.loads((replacement / "triton-call-replacement.json").read_text())
        if report.get("w8a8_enabled"):
            entry = re.search(r"func\.func @forward\(%arg0: memref<(\d+)xf32>,\s*%arg1: memref<(\d+)xi8>", text)
            if entry is None:
                raise ValueError("W8A8 main graph does not expose f32+i8 parameter arenas")
            layout = report.get("parameter_layout") or []
            f32_expected = sum(math.prod(p["shape"]) for p in layout if "Float32" in p.get("dtype", ""))
            i8_expected = sum(math.prod(p["shape"]) for p in layout if "Int8" in p.get("dtype", ""))
            if int(entry.group(1)) != f32_expected or int(entry.group(2)) != i8_expected:
                raise ValueError("W8A8 main graph arena sizes disagree with parameter layout")
            return {"source": str(source), "mode": "w8a8", "f32_elements": f32_expected,
                    "i8_elements": i8_expected, "matches_parameter_layout": True}
    entry = re.search(r"func\.func @forward\(%arg0: memref<(\d+)xf32>", text)
    if entry is None or int(entry.group(1)) != ELEMENTS:
        raise ValueError("main graph flat weight buffer has the wrong size")
    slices = [(int(offset), int(length)) for offset, length in re.findall(
        r"memref\.subview %arg0\[(\d+)\] \[(\d+)\] \[1\]", text)]
    records = json.loads(params.read_text())
    if len(slices) != len(records) or len(records) != 200:
        raise ValueError("main graph weight slice count differs from captured parameters")
    cursor = 0
    for index, ((offset, length), record) in enumerate(zip(slices, records)):
        if record["index"] != index or offset != cursor or length != record["elements"]:
            raise ValueError(f"main graph weight slice {index} differs from captured parameter")
        cursor += length
    if cursor != ELEMENTS:
        raise ValueError("main graph weight slices do not cover the flat buffer")
    return {"source": str(source), "sections": len(slices),
            "elements": cursor, "matches_captured_order": True}


def _parse_forward_memrefs(main_mlir: Path | None) -> list[dict]:
    """Read ranked input memrefs from the lowered @forward declaration."""
    if main_mlir is None or not main_mlir.is_file():
        return []
    text = main_mlir.read_text()
    match = re.search(r"func\.func @forward\((.*?)\)\s*->", text, re.S)
    if not match:
        return []
    # Lowered main.ciface.mlir uses ranked memref<dimsxdtype> types without
    # nested angle brackets, so a comma split is sufficient here.
    specs = []
    for index, part in enumerate(match.group(1).split(",")):
        found = re.search(r"%arg\d+\s*:\s*memref<([^>]+)>", part.strip())
        if not found:
            continue
        body = found.group(1)
        dtype_match = re.search(r"(f32|i8|i32|f16|i64)$", body)
        if dtype_match is None:
            raise ValueError(f"cannot parse @forward memref dtype: {body}")
        dtype = dtype_match.group(1)
        dims = body[:dtype_match.start()].rstrip("x")
        shape = [int(dim) for dim in dims.split("x") if dim]
        specs.append({"index": index, "rank": len(shape), "shape": shape,
                      "dtype": dtype})
    return specs


def _descriptor_code(name: str, spec: dict, pointer: str) -> list[str]:
    rank, shape = spec["rank"], spec["shape"]
    if rank not in (1, 2, 3, 4):
        raise ValueError(f"unsupported workspace rank {rank} for {name}")
    lines = [f"  MemRef{rank} {name} = {{(void *){pointer}, (void *){pointer}, 0, {{" +
             ", ".join(str(v) for v in shape) + "}, {" ]
    strides = []
    stride = 1
    for value in reversed(shape):
        strides.append(stride); stride *= value
    lines[-1] += ", ".join(str(v) for v in reversed(strides)) + "}};"
    return lines


def main_source(has_image: bool, expected_top1: int | None = None,
                hang_diagnostics: bool = False, forward_specs: list[dict] | None = None,
                w8a8: bool = False, f32_bytes: int = WEIGHT_BYTES,
                i8_bytes: int = 0) -> str:
    image_declaration = (
        'extern const unsigned char input_image_raw[];\n'
        'extern const unsigned char input_image_end[];\n'
        if has_image else ""
    )
    image_init = (
        '  nr_copy_bytes(image, input_image_raw, sizeof(image));\n'
        if has_image else
        '  /* RA startup zeroes the ordinary .bss image buffer. */\n'
    )
    top1_check = (
        f'  nr_puts(best == {expected_top1} ? "[vit] top1 PASS\\r\\n" : '
        '"[vit] top1 FAIL\\r\\n");\n'
        f'  return best == {expected_top1} ? 0 : 1;'
        if expected_top1 is not None else '  return 0;'
    )
    specs = forward_specs or []
    # @forward's first two inputs in W8A8 mode are packed f32/i8 arenas,
    # followed by the image and explicit quantization workspaces.  The output
    # descriptor is still the first C-interface argument.
    if w8a8:
        if len(specs) < 2 or specs[0]["dtype"] != "f32" or specs[1]["dtype"] != "i8":
            raise ValueError("W8A8 @forward must begin with f32 and i8 parameter arenas")
        arg_decls = ["MemRef2 *output"] + [f"MemRef{s['rank']} *arg{i}" for i, s in enumerate(specs)]
        arena_decl = f'''__asm__(".section .workspace,\\"aw\\",@nobits\\n"
        ".balign 64\\n"
        "weight_arena_f32_raw:\\n"
        ".skip {align64(f32_bytes)}\\n"
        "weight_arena_f32_end:\\n"
        ".balign 64\\n"
        "weight_arena_i8_raw:\\n"
        ".skip {align64(i8_bytes)}\\n"
        "weight_arena_i8_end:\\n"
        ".previous\\n");
extern unsigned char weight_arena_f32_raw[] __asm__("weight_arena_f32_raw");
extern unsigned char weight_arena_i8_raw[] __asm__("weight_arena_i8_raw");'''
        declarations = ", ".join(arg_decls)
        setup = ["  MemRef1 f32_weights = make_1(weight_arena_f32_raw, %d);" % (f32_bytes // 4),
                 "  MemRef1 i8_weights = make_1(weight_arena_i8_raw, %d);" % i8_bytes,
                 "  MemRef4 input = make_4(image, 1, 3, 224, 224);",
                 "  MemRef2 output = make_2(logits, 1, 1000);"]
        # Build explicit descriptors for each workspace argument.  Arena/image
        # descriptors are replaced by their corresponding packed buffers.
        for i, spec in enumerate(specs):
            if i == 0:
                setup.append("  MemRef1 *arg0 = &f32_weights;")
            elif i == 1:
                setup.append("  MemRef1 *arg1 = &i8_weights;")
            elif i == 2:
                setup.append("  MemRef4 *arg2 = &input;")
            else:
                bytes_count = math.prod(spec["shape"]) * {"f32": 4, "i8": 1, "i32": 4}[spec["dtype"]]
                setup.append(f"  static unsigned char workspace_{i}[{align64(bytes_count)}] __attribute__((section(\".workspace\"), aligned(64)));" )
                setup += _descriptor_code(f"workspace_desc_{i}", spec, f"workspace_{i}")
                setup.append(f"  MemRef{spec['rank']} *arg{i} = &workspace_desc_{i};")
        call_args = ", ".join(["&output"] + [f"arg{i}" for i in range(len(specs))])
        launch_body = "\n".join(setup)
        return f'''#include "support.h"
#include "nr_runtime.h"

{arena_decl}
static float image[1 * 3 * 224 * 224] __attribute__((aligned(64)));
static float logits[1 * 1000] __attribute__((aligned(64)));
{image_declaration}
extern void _mlir_ciface_forward({declarations});

int launch(void) {{
{image_init}{launch_body}
  nr_puts("[vit] forward start\\r\\n");
  _mlir_ciface_forward({call_args});
  nr_puts("[vit] graph return\\r\\n");
  const float *values = (const float *)output.aligned + output.offset;
  unsigned best = 0; float best_value = values[0];
  for (unsigned i = 1; i < 1000; ++i) if (values[i] > best_value) {{ best = i; best_value = values[i]; }}
  union {{ float f; uint32_t u; }} bits = {{ best_value }};
  nr_puts("[vit] class="); nr_hex32(best); nr_puts(" logit_bits="); nr_hex32(bits.u); nr_puts("\\r\\n");
{top1_check}
}}
'''

    return f'''#include "support.h"
#include "nr_runtime.h"

/* The loader preloads this NOLOAD arena from weights-load.bin. */
__asm__(".section .workspace,\\"aw\\",@nobits\\n"
        ".balign 64\\n"
        "weight_arena_raw:\\n"
        ".skip {WEIGHT_BYTES}\\n"
        "weight_arena_end:\\n"
        ".previous\\n");
extern unsigned char weight_arena_raw[] __asm__("weight_arena_raw");
extern unsigned char weight_arena_end[] __asm__("weight_arena_end");
static float image[1 * 3 * 224 * 224] __attribute__((aligned(64)));
static float logits[1 * 1000] __attribute__((aligned(64)));
{image_declaration}
extern void _mlir_ciface_forward(MemRef2 *, MemRef1 *, MemRef4 *);

int launch(void) {{
{image_init}  MemRef1 weights = make_1(weight_arena_raw, {ELEMENTS});
  MemRef4 input = make_4(image, 1, 3, 224, 224);
  MemRef2 output = make_2(logits, 1, 1000);
  nr_puts("[vit] forward start\\r\\n");
#ifdef NR_HANG_DIAGNOSTICS
  nr_diag_reset(0);
#endif
  _mlir_ciface_forward(&output, &weights, &input);
  nr_puts("[vit] graph return\\r\\n");
#ifdef NR_HANG_DIAGNOSTICS
  nr_diag_mark(NR_DIAG_GRAPH_RETURN, 0);
#endif
  /* A returned memref descriptor may point to graph-allocated storage. */
  const float *values = (const float *)output.aligned + output.offset;
  unsigned best = 0;
  float best_value = values[0];
  for (unsigned i = 1; i < 1000; ++i)
    if (values[i] > best_value) {{ best = i; best_value = values[i]; }}
  union {{ float f; uint32_t u; }} bits = {{ best_value }};
  nr_puts("[vit] class="); nr_hex32(best);
  nr_puts(" logit_bits="); nr_hex32(bits.u);
  nr_puts("\\r\\n");
{top1_check}
}}
'''


def run(command: list, steps: dict, name: str, *, stdin=None, stdout=None) -> None:
    with_output = stdin is None and stdout is None
    result = subprocess.run([str(item) for item in command], stdin=stdin,
                            stdout=subprocess.PIPE if with_output else stdout,
                            stderr=subprocess.PIPE, text=False)
    steps[name] = {"returncode": result.returncode,
                   "stderr": result.stderr.decode(errors="replace")[-3000:]}
    if with_output and result.stdout:
        steps[name]["stdout"] = result.stdout.decode(errors="replace")[-1000:]
    if result.returncode:
        raise RuntimeError(f"{name} failed: {steps[name]['stderr']}")


def defined_symbols(nm: Path, elf: Path) -> dict[str, int]:
    lines = subprocess.check_output([str(nm), "--defined-only", str(elf)], text=True)
    return {fields[2]: int(fields[0], 16) for line in lines.splitlines()
            if len(fields := line.split()) == 3}


def write_load_plan(output: Path, elf: Path, binary: Path, manifest: dict,
                    nm: Path) -> dict:
    symbols = defined_symbols(nm, elf)
    if symbols.get("_start") != BOOT_BASE:
        raise ValueError("ELF boot or weight address disagrees with the NR layout")
    arena_segments = []
    if manifest.get("mode") == "w8a8":
        f32 = next(a for a in manifest["arenas"] if a.get("dtype") == "f32")
        i8 = next(a for a in manifest["arenas"] if a.get("dtype") == "i8")
        if symbols.get("weight_arena_f32_raw") != WORKSPACE_BASE:
            raise ValueError("ELF FP32 arena address disagrees with the NR layout")
        f32_end = symbols.get("weight_arena_f32_end")
        i8_start = symbols.get("weight_arena_i8_raw")
        if f32_end != WORKSPACE_BASE + align64(f32["bytes"]) or i8_start != f32_end:
            raise ValueError("ELF mixed arena boundaries disagree with packed weights")
        if symbols.get("weight_arena_i8_end") != i8_start + align64(i8["bytes"]):
            raise ValueError("ELF INT8 arena length disagrees with packed weights")
        arena_segments = [
            {"name": "weights-f32", "file": f32["load_file"],
             "address": WORKSPACE_BASE, "size": f32["load_bytes"],
             "sha256": f32["load_sha256"]},
            {"name": "weights-i8", "file": i8["load_file"],
             "address": i8_start, "size": i8["load_bytes"],
             "sha256": i8["load_sha256"]},
        ]
        arena_end = i8_start + i8["load_bytes"]
    else:
        if symbols.get("weight_arena_raw") != WORKSPACE_BASE:
            raise ValueError("ELF boot or weight address disagrees with the NR layout")
        if symbols.get("weight_arena_end") != WORKSPACE_BASE + WEIGHT_BYTES:
            raise ValueError("ELF weight arena length disagrees with the packed weights")
        arena_segments = [{"name": "weights", "file": manifest["load_file"],
                           "address": WORKSPACE_BASE, "size": manifest["load_bytes"],
                           "sha256": manifest["load_sha256"]}]
        arena_end = WORKSPACE_BASE + manifest["load_bytes"]
    if symbols.get("__workspace_end", 0) < arena_end:
        raise ValueError("padded load segment exceeds linked workspace")
    if binary.stat().st_size <= 0 or binary.stat().st_size >= 0x30000000:
        raise ValueError("boot image exceeds LOW DDR")
    boot_load = output / "vit_model-load.bin"
    with binary.open("rb") as source, boot_load.open("wb") as dest:
        shutil.copyfileobj(source, dest)
        dest.write(bytes(align64(binary.stat().st_size) - binary.stat().st_size))
    segments = [
        {"name": "model", "file": "image.bin", "local_file": boot_load.name,
         "address": BOOT_BASE, "size": boot_load.stat().st_size,
         "sha256": digest_file(boot_load)},
    ] + arena_segments
    lines = ["version = 1", "ddr_base = 0x80000000", "ddr_size = 0x400000000",
             "alignment = 64"]
    for segment in segments:
        lines += ["", "[[segments]]", f'name = "{segment["name"]}"',
                  f'file = "{segment["file"]}"',
                  f'address = 0x{segment["address"]:x}',
                  f'size = {segment["size"]}',
                  f'sha256 = "{segment["sha256"]}"']
    (output / "ddr-load.plan").write_text("\n".join(lines) + "\n")
    return {"segments": segments, "weight_arena_start": hex(WORKSPACE_BASE),
            "weight_arena_end": hex(arena_end),
            "workspace_end": hex(symbols["__workspace_end"]),
            "workspace_bytes": symbols["__workspace_end"] - WORKSPACE_BASE,
            "bss_bytes": symbols["__bss_end"] - symbols["__bss_start"],
            "low_heap_start": hex(symbols.get("__heap_start", 0)),
            "low_heap_end": hex(symbols.get("__heap_end", 0)),
            "low_heap_capacity_bytes": (symbols["__heap_end"] -
                                        symbols["__heap_start"])}


def build(args, output: Path, report: dict) -> None:
    repo = args.repo_root.resolve()
    vit = Path(__file__).resolve().parents[1]
    nr = repo / "examples/FPGA-BOSCAME/common/nr"
    tools = repo / "examples/FPGA-BOSCAME/tools"
    llvm = args.llvm_bin or repo / "llvm/build-2d26/bin"
    clang, llc = llvm / "clang", llvm / "llc"
    objcopy, nm = llvm / "llvm-objcopy", llvm / "llvm-nm"
    steps = report["steps"]
    flags = ["--target=riscv64-unknown-elf", "-march=rv64gc_zicbom",
             "-mabi=lp64d", "-mcmodel=medany", "-mno-relax", "-O2", "-nostdlib",
             "-ffreestanding", "-fno-builtin", "-fno-pie", "-fno-vectorize",
             "-fno-slp-vectorize", "-ffp-contract=off", f"-I{vit}", f"-I{nr}"]

    has_image = args.input_image is not None or args.input_seed is not None
    source = output / "model_main.c"
    w8a8 = report.get("weights", {}).get("mode") == "w8a8"
    main_mlir = args.main_graph_mlir
    if main_mlir is None:
        candidate = args.main_graph_ir.with_name("main.ciface.mlir")
        main_mlir = candidate if candidate.is_file() else None
    forward_specs = _parse_forward_memrefs(main_mlir) if w8a8 else None
    arenas = report.get("weights", {}).get("arenas", [])
    f32_bytes = next((a["bytes"] for a in arenas if a.get("dtype") == "f32"), WEIGHT_BYTES)
    i8_bytes = next((a["bytes"] for a in arenas if a.get("dtype") == "i8"), 0)
    source.write_text(main_source(has_image, args.expected_top1,
                                  args.hang_diagnostics, forward_specs,
                                  w8a8, f32_bytes, i8_bytes))
    compile_flags = ([*flags, "-DNR_HANG_DIAGNOSTICS"]
                     if args.hang_diagnostics else flags)
    if has_image:
        image_copy = output / "input-image.bin"
        if args.input_image is not None:
            if args.input_image.stat().st_size != IMAGE_BYTES:
                raise ValueError(f"input image must contain {IMAGE_BYTES} raw FP32 bytes")
            if args.input_image.resolve() != image_copy.resolve():
                shutil.copyfile(args.input_image, image_copy)
            input_mode = "raw-fp32"
        else:
            import numpy as np
            pixels = np.random.default_rng(args.input_seed).uniform(
                -1.0, 1.0, (1, 3, 224, 224)).astype(np.float32)
            image_copy.write_bytes(pixels.tobytes(order="C"))
            input_mode = "uniform-seed"
        report["input"] = {"mode": input_mode, "shape": [1, 3, 224, 224],
                           "bytes": IMAGE_BYTES, "file": image_copy.name,
                           "sha256": digest_file(image_copy),
                           "expected_top1": args.expected_top1}
        if args.input_seed is not None:
            report["input"]["seed"] = args.input_seed
        image_asm = output / "input_image.S"
        image_asm.write_text('.section .rodata.input_image,"a",@progbits\n'
                             '.balign 64\n.globl input_image_raw\n'
                             'input_image_raw:\n'
                             f'.incbin "{image_copy.resolve()}"\n'
                             '.globl input_image_end\ninput_image_end:\n')
        run([clang, *flags, "-c", image_asm, "-o", output / "input_image.o"],
            steps, "compile_input_image")
    else:
        report["input"] = {"mode": "zeros", "shape": [1, 3, 224, 224],
                           "bytes": IMAGE_BYTES,
                           "sha256": hashlib.sha256(bytes(IMAGE_BYTES)).hexdigest(),
                           "expected_top1": args.expected_top1}
    run([clang, *compile_flags, "-c", source, "-o", output / "model_main.o"],
        steps, "compile_main")

    def compile_graph(source_ir: Path, stem: str) -> Path:
        assembly = output / f"{stem}.s"
        encoded = output / f"{stem}.encoded.s"
        restricted = output / f"{stem}.nr.S"
        obj = output / f"{stem}.nr.o"
        run([llc, source_ir, "-O2", "-filetype=asm", "-mtriple=riscv64",
             "-target-abi=lp64d", "-mattr=+m,+a,+f,+d,+c,-v,+xboscame",
             "-code-model=medium", "-o", assembly], steps, f"{stem}_llc")
        with assembly.open("rb") as source_file, encoded.open("wb") as dest_file:
            run([sys.executable, tools / "ame_to_word.py"], steps,
                f"{stem}_encode_ame", stdin=source_file, stdout=dest_file)
        with encoded.open("rb") as source_file, restricted.open("wb") as dest_file:
            run([sys.executable, tools / "restrict_fpga_assembly.py"], steps,
                f"{stem}_restrict", stdin=source_file, stdout=dest_file)
        run([clang, *flags, "-c", restricted, "-o", obj],
            steps, f"{stem}_assemble")
        return obj

    subgraph_object = compile_graph(args.graph_ir, "vit")
    main_graph_object = compile_graph(args.main_graph_ir, "forward")
    # Compile the generated bridge explicitly, so the linked model ABI is
    # auditable even though the archive also contains a copy of that object.
    adapter_flags = list(compile_flags)
    if args.trace_ops:
        adapter_flags.append("-DVIT_TRACE_OPS=1")
        # The same trace image also records RA cycle counters immediately
        # before and after each adapter.  This makes per-operator timing
        # independent of UART relay wall-clock jitter; the cycle frequency is
        # supplied by the selected UVHS runtime profile.
        adapter_flags.append("-DVIT_TRACE_TIMING=1")
    run([clang, *adapter_flags, "-c", args.adapters,
         "-o", output / "vit_triton_adapters.o"],
        steps, "compile_adapters")
    runtime_objects = []
    for name in ("crt.S", "nr_runtime.c", "nr_memory.c", "nr_math.c",
                 "ame_sync.c", "nr_copy.S"):
        obj = output / (Path(name).stem + ".o")
        source_flags = ["-march=rv64gcv_zicbom" if name == "nr_copy.S" and
                        flag.startswith("-march=") else flag for flag in compile_flags]
        run([clang, *source_flags, "-c", nr / name, "-o", obj],
            steps, f"runtime_{name}")
        runtime_objects.append(obj)
    elf = output / "vit_model.elf"
    linker = args.linker or shutil.which("ld.lld")
    if not linker:
        raise FileNotFoundError("ld.lld is required")
    run([linker, "-m", "elf64lriscv", "--gc-sections", "-T", nr / "nr.ld",
         f"-Map={output / 'vit_model.map'}", "-o", elf,
         output / "model_main.o", main_graph_object, subgraph_object,
         output / "vit_triton_adapters.o",
         *([output / "input_image.o"] if has_image else []),
         *runtime_objects, args.archive], steps, "link")
    binary = output / "vit_model.bin"
    run([objcopy, "-O", "binary", elf, binary], steps, "objcopy")
    run([sys.executable, tools / "check_nr_elf.py", elf,
         "--objdump", llvm / "llvm-objdump",
         "--output", output / "elf-audit.json"], steps, "elf_audit")
    layout = write_load_plan(output, elf, binary, report["weights"], nm)
    report.update({"status": "PASS_STATIC", "image": {
        "elf": str(elf), "elf_bytes": elf.stat().st_size,
        "bin": str(binary), "bin_bytes": binary.stat().st_size,
        "bin_sha256": digest_file(binary), "ddr_plan": str(output / "ddr-load.plan"),
        **layout}, "execution": "Static build and ELF audit only; no FPGA run",
        "performance_note": "ViT-B/16 is roughly 17 GFLOPs; patch6 board execution uses a 5.5296 MHz RA clock and may take a long time."})


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path,
                        default=Path(__file__).resolve().parents[4])
    parser.add_argument("--params", type=Path, required=True)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--graph-ir", type=Path, required=True,
                        help="lowered ViT subgraph LLVM IR defining vit")
    parser.add_argument("--main-graph-ir", type=Path, required=True,
                        help="lowered flat-parameter wrapper IR defining forward")
    parser.add_argument("--main-graph-mlir", type=Path,
                        help="main.ciface.mlir used to verify flat-buffer slice order")
    parser.add_argument("--subgraph-mlir", type=Path,
                        help="replacement MLIR for checking the 201-input ViT ABI")
    parser.add_argument("--archive", type=Path, required=True)
    parser.add_argument("--adapters", type=Path, required=True)
    parser.add_argument("--replacement", type=Path,
                        help="W8A8 replacement directory (mixed parameter layout)")
    parser.add_argument("--output", type=Path, required=True)
    inputs = parser.add_mutually_exclusive_group()
    inputs.add_argument("--input-image", type=Path,
                        help="optional raw [1,3,224,224] little-endian FP32 tensor")
    inputs.add_argument("--input-seed", type=int,
                        help="generate host-runner-compatible uniform [-1,1] FP32 image")
    parser.add_argument("--expected-top1", type=int,
                        help="optional reference class; UART reports top1 PASS/FAIL")
    parser.add_argument("--trace-ops", action="store_true",
                        help="print BEGIN/END for each graph Triton call on UART")
    parser.add_argument("--hang-diagnostics", action="store_true",
                        help="enable NH hang-watch mailbox and per-call RA diagnostics")
    parser.add_argument("--llvm-bin", type=Path)
    parser.add_argument("--linker")
    args = parser.parse_args()
    if args.expected_top1 is not None and not 0 <= args.expected_top1 < 1000:
        parser.error("--expected-top1 must be in [0, 999]")
    args.output.mkdir(parents=True, exist_ok=True)
    report = {"status": "INCOMPLETE", "steps": {},
              "graph_ir": str(args.graph_ir),
              "main_graph_ir": str(args.main_graph_ir),
              "checkpoint": str(args.checkpoint)}
    try:
        for path in (args.params, args.checkpoint, args.graph_ir,
                     args.main_graph_ir,
                     args.archive, args.adapters):
            if not path.is_file():
                raise FileNotFoundError(path)
        report["operator_trace"] = {"enabled": args.trace_ops,
                                    "adapter_sha256": digest_file(args.adapters),
                                    "hang_diagnostics": args.hang_diagnostics}
        if args.trace_ops:
            report["operator_trace"]["call_count"] = trace_call_count(args.adapters)
        report["subgraph_abi"] = verify_subgraph_abi(
            args.graph_ir, args.subgraph_mlir, args.replacement)
        report["main_weight_layout"] = verify_main_weight_layout(
            args.main_graph_ir, args.main_graph_mlir, args.params, args.replacement)
        report["weights"] = pack_weights(args.params, args.checkpoint, args.output,
                                          args.replacement)
        build(args, args.output, report)
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        report.update({"status": "FAILED", "error": str(error)})
    (args.output / "model-image.json").write_text(json.dumps(report, indent=2) + "\n")
    summary = {k: v for k, v in report.items() if k not in ("steps", "weights")}
    if "weights" in report:
        summary["weights"] = {k: v for k, v in report["weights"].items()
                              if k != "sections"}
    print(json.dumps(summary, indent=2))
    return 0 if report["status"] == "PASS_STATIC" else 1


if __name__ == "__main__":
    sys.exit(main())
