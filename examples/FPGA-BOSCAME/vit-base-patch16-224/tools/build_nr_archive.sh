#!/usr/bin/env bash
# Archive already-built NR Triton objects and the graph-facing ABI adapter.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TRITON_BUILD="${TRITON_BUILD:-$ROOT/build/kernels}"
ADAPTERS="${ADAPTERS:-$ROOT/build/replacement/vit_triton_adapters.c}"
OUT="${OUT:-$ROOT/build/nr-archive}"
CC="${RISCV_CC:-clang --target=riscv64-unknown-elf}"
read -r -a CC_WORDS <<< "$CC"
AR="${LLVM_AR:-llvm-ar}"
if [[ ! -f "$ADAPTERS" ]]; then echo "missing $ADAPTERS" >&2; exit 1; fi
mapfile -t ROOT_CASES < <(grep -o '_mlir_ciface_kernel_[A-Za-z0-9_]*' "$ADAPTERS" | sed 's/_mlir_ciface_kernel_//' | sort -u)
((${#ROOT_CASES[@]})) || { echo "adapter has no Triton calls" >&2; exit 1; }
# A composed graph adapter can call another ciface adapter.  Resolve that
# small dependency closure before archiving; patch embedding, for example,
# calls the dedicated 196x768x768 linear kernel after its im2col stage.
declare -A seen_cases=()
CASES=()
add_case() {
  local name="$1"
  [[ ${seen_cases[$name]+yes} ]] && return
  seen_cases[$name]=1
  CASES+=("$name")
}
for name in "${ROOT_CASES[@]}"; do add_case "$name"; done
for ((index = 0; index < ${#CASES[@]}; ++index)); do
  name="${CASES[$index]}"
  adapter="$TRITON_BUILD/$name/adapter.c"
  [[ -f "$adapter" ]] || continue
  while IFS= read -r dependency; do
    [[ -n "$dependency" ]] && add_case "$dependency"
  done < <(grep -o '_mlir_ciface_kernel_[A-Za-z0-9_]*' "$adapter" |
           sed 's/_mlir_ciface_kernel_//' | sort -u)
done
rm -rf "$OUT"; mkdir -p "$OUT"
objects=()
for name in "${CASES[@]}"; do
  test -f "$TRITON_BUILD/$name/nr/kernel.o" || { echo "missing NR kernel $name" >&2; exit 1; }
  test -f "$TRITON_BUILD/$name/nr/adapter.o" || { echo "missing NR adapter $name" >&2; exit 1; }
  cp "$TRITON_BUILD/$name/nr/kernel.o" "$OUT/$name.kernel.o"
  cp "$TRITON_BUILD/$name/nr/adapter.o" "$OUT/$name.ciface.o"
  objects+=("$OUT/$name.kernel.o" "$OUT/$name.ciface.o")
done
# The model adapter writes descriptors and calls each per-case C ABI adapter.
# A final image still needs the NR runtime and graph entry generated by the
# caller; this archive is the auditable kernel layer used by that link.
"${CC_WORDS[@]}" -march=rv64gc_zicbom -mabi=lp64d -mno-relax -O2 -ffreestanding -fno-builtin -I"$ROOT" -I"$ROOT/../common/nr" -c "$ADAPTERS" -o "$OUT/vit_triton_adapters.o"
objects+=("$OUT/vit_triton_adapters.o")
"$AR" rcsD "$OUT/libvit_triton_nr.a" "${objects[@]}"
printf '%s kernels -> %s\n' "${#CASES[@]}" "$OUT/libvit_triton_nr.a"
